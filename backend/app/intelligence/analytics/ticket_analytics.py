from __future__ import annotations

from typing import Iterable

from pydantic import BaseModel, ConfigDict, Field

from app.intelligence.schemas.ticket import Ticket
from app.intelligence.schemas.workflow import WorkflowEvent
from app.intelligence.workflow.handoffs import HandoffRecord
from app.intelligence.workflow.metrics import (
    WAITING_STATUSES,
    WorkflowMetrics,
)


HIGH_PRIORITY_VALUES = {"high", "highest", "blocker"}


class TicketAnalytics(BaseModel):
    """
    Dashboard-ready operational analytics for a single support ticket.

    This model contains derived operational metrics only.
    It does not perform ML, NLP, retrieval, or root-cause inference.
    """

    model_config = ConfigDict(
        extra="forbid",
        str_strip_whitespace=True,
        validate_assignment=True,
    )

    ticket_id: str
    project: str
    issue_num: int
    issue_type: str
    priority: str
    status: str

    lifecycle_seconds: float = Field(ge=0)
    active_seconds: float = Field(ge=0)
    waiting_seconds: float = Field(ge=0)

    active_ratio: float = Field(ge=0, le=1)
    waiting_ratio: float = Field(ge=0, le=1)

    transition_count: int = Field(ge=0)
    unique_status_count: int = Field(ge=0)
    unique_assignee_count: int = Field(ge=0)
    handoff_count: int = Field(ge=0)

    is_high_priority: bool
    is_waiting: bool


def _enum_value(value: object) -> str:
    """
    Return the raw value for Enum-like objects, otherwise stringify the value.
    """
    raw_value = getattr(value, "value", value)
    return str(raw_value)


def build_ticket_analytics(
    ticket: Ticket,
    workflow_metrics: WorkflowMetrics,
    handoffs: Iterable[HandoffRecord] | None = None,
) -> TicketAnalytics:
    """
    Build dashboard-ready analytics for one canonical ticket.

    Parameters
    ----------
    ticket:
        Canonical ticket representation.

    workflow_metrics:
        Workflow-level metrics already calculated by workflow.metrics.

    handoffs:
        Handoff records generated by workflow.handoffs.
        Only records belonging to this ticket are counted.

    Returns
    -------
    TicketAnalytics
        Structured operational analytics for dashboard/API consumption.
    """

    lifecycle_seconds = max(float(workflow_metrics.lifecycle_seconds), 0.0)
    active_seconds = max(float(workflow_metrics.active_seconds), 0.0)
    waiting_seconds = max(float(workflow_metrics.waiting_seconds), 0.0)

    if lifecycle_seconds > 0:
        active_ratio = min(active_seconds / lifecycle_seconds, 1.0)
        waiting_ratio = min(waiting_seconds / lifecycle_seconds, 1.0)
    else:
        active_ratio = 0.0
        waiting_ratio = 0.0

    ticket_priority = _enum_value(ticket.priority)
    ticket_status = _enum_value(ticket.status)

    high_priority = ticket_priority.lower() in HIGH_PRIORITY_VALUES

    waiting_statuses = {
        str(status).strip().lower()
        for status in WAITING_STATUSES
    }
    is_waiting = ticket_status.strip().lower() in waiting_statuses

    handoff_count = 0

    if handoffs is not None:
        handoff_count = sum(
            1
            for handoff in handoffs
            if handoff.ticket_id == ticket.ticket_id
        )

    return TicketAnalytics(
        ticket_id=ticket.ticket_id,
        project=ticket.project,
        issue_num=ticket.issue_num,
        issue_type=ticket.issue_type,
        priority=ticket_priority,
        status=ticket_status,
        lifecycle_seconds=lifecycle_seconds,
        active_seconds=active_seconds,
        waiting_seconds=waiting_seconds,
        active_ratio=active_ratio,
        waiting_ratio=waiting_ratio,
        transition_count=max(int(workflow_metrics.transition_count), 0),
        unique_status_count=max(
            int(workflow_metrics.unique_status_count),
            0,
        ),
        unique_assignee_count=max(
            int(workflow_metrics.unique_assignee_count),
            0,
        ),
        handoff_count=handoff_count,
        is_high_priority=high_priority,
        is_waiting=is_waiting,
    )
